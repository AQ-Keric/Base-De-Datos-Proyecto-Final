-- Incremento de usos en barricas de roble
CREATE OR REPLACE TRIGGER CA_EA_ST_IY_TRG_USO_BARRICA
AFTER UPDATE OF id_contenedor ON CA_EA_ST_IY_LOTE
FOR EACH ROW
DECLARE
    v_material VARCHAR2(50);
BEGIN
    SELECT material INTO v_material 
    FROM CA_EA_ST_IY_CONTENEDORES 
    WHERE id_contenedor = :NEW.id_contenedor;

    IF UPPER(v_material) LIKE '%ROBLE%' OR UPPER(v_material) LIKE '%BARRICA%' THEN
        UPDATE CA_EA_ST_IY_CONTENEDORES
        SET nro_usos = nro_usos + 1
        WHERE id_contenedor = :NEW.id_contenedor;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN NULL;
END;
/

