-- 3. Secuencia y triggers
CREATE SEQUENCE CA_EA_ST_IY_SEQ_AUDITORIA START WITH 1 INCREMENT BY 1;

-- Auditoria de movimientos de trasvasijado
CREATE OR REPLACE TRIGGER CA_EA_ST_IY_TRG_AUDITORIA_MOVIMIENTO
AFTER UPDATE OF id_contenedor ON CA_EA_ST_IY_LOTE
FOR EACH ROW
BEGIN
    INSERT INTO CA_EA_ST_IY_AUDITORIA_MOVIMIENTOS (
        id_log, id_lote, usuario_bd, fecha_movimiento, 
        contenedor_origen, contenedor_destino, accion
    ) VALUES (
        CA_EA_ST_IY_SEQ_AUDITORIA.NEXTVAL,
        :OLD.id_lote,
        USER,
        SYSDATE,
        :OLD.id_contenedor,
        :NEW.id_contenedor,
        'TRASVASIJADO: Cambio de contenedor'
    );
END;
/

-- Incremento de usos en barricas de roble
CREATE OR REPLACE TRIGGER CA_EA_ST_IY_TRG_USO_BARRICA
AFTER UPDATE OF id_contenedor ON CA_EA_ST_IY_LOTE
FOR EACH ROW
DECLARE
    v_material VARCHAR2(50);
BEGIN
    SELECT material INTO v_material 
    FROM CA_EA_ST_IY_CONTENEDORES 
    WHERE id_contenedor = :NEW.id_contenedor;

    IF UPPER(v_material) LIKE '%ROBLE%' OR UPPER(v_material) LIKE '%BARRICA%' THEN
        UPDATE CA_EA_ST_IY_CONTENEDORES
        SET nro_usos = nro_usos + 1
        WHERE id_contenedor = :NEW.id_contenedor;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN NULL;
END;
/

